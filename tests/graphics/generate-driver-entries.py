"""Generate the native driver table/remapping from the reviewed call inventory."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--inventory', type=Path, default=Path('tests/graphics/native-entrypoints.json'))
parser.add_argument('--output', type=Path, default=Path('hw/arm/gles-host-driver-entries.c.inc'))
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
inventory = json.loads(args.inventory.read_text())
lines = ['/* SPDX-License-Identifier: GPL-2.0-or-later',
         ' * Generated by tests/graphics/generate-driver-entries.py.',
         ' * Intentionally included repeatedly for declarations, loading and remapping.',
         ' */', '#if defined(GLES_DRIVER_EXTENSIONS)']
lines += [f'GLES_DRIVER_EXTENSION({name})' for name in inventory['dynamic_gl_extensions']]
lines += ['#elif defined(GLES_DRIVER_REMAP)']
for group in ['egl', 'gl']:
    lines += [f'#define {name} gles_driver.raw_{name}' for name in inventory[group]]
lines += ['#else']
for group in ['egl', 'gl']:
    lines += [f'GLES_DRIVER_{group.upper()}({name})' for name in inventory[group]]
lines += ['#endif', '']
text = '\n'.join(lines)
if args.check:
    if args.output.read_text() != text:
        parser.exit(1, 'FAIL generated native driver entries differ\n')
else:
    args.output.write_text(text)
print('PASS generated native driver entries')

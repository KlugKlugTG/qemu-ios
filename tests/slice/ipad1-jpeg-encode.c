static void tables(JpegHuff huff[4])
{
    memset(huff, 0, 4 * sizeof(*huff));
    for (int c = 0; c < 2; c++) {       /* DC0, DC1, AC0, AC1 as the block holds them */
        memcpy(huff[c].bits, dc_bits[c], 16);
        huff[c].nvals = 12;
        for (int i = 0; i < 12; i++) {
            huff[c].vals[i] = i;
        }
        memcpy(huff[2 + c].bits, ac_bits[c], 16);
        huff[2 + c].nvals = 162;
        memcpy(huff[2 + c].vals, ac_vals[c], 162);
    }
}

/* yuvs: a luma ramp across, chroma bands down. */
static uint8_t Y(unsigned x, unsigned y) { return 40 + x * 3 + y; }
static uint8_t U(unsigned x, unsigned y) { return y < H / 2 ? 90 : 170; }
static uint8_t V(unsigned x, unsigned y) { return x < W / 2 ? 200 : 60; }

static void check(bool v2, const uint8_t qt[2][64], int tol)
{
    uint8_t src[W * H * 2], dst[1 << 16], pix[W * H * 3];
    JpegHuff huff[4];
    bool overflow;

    for (unsigned y = 0; y < H; y++) {
        for (unsigned x = 0; x < W; x++) {
            uint8_t *p = src + (y * W + x) * 2;
            p[0] = Y(x, y);
            p[1] = (x & 1) ? V(x, y) : U(x, y);
        }
    }
    tables(huff);
    size_t len = jpeg_encode(src, W, H, W * 2, v2, qt, huff, dst, sizeof(dst), &overflow);
    assert(!overflow && len > 600 && len < sizeof(dst));

    /* DQT 0 (after SOI and its marker, length and table id) is the natural-order table in zigzag order. */
    assert(dst[2] == 0xff && dst[3] == 0xdb && dst[6] == 0);
    for (int k = 0; k < 64; k++) {
        assert(dst[7 + k] == qt[0][zigzag[k]]);
    }

    struct jpeg_decompress_struct d;
    struct jpeg_error_mgr err;
    d.err = jpeg_std_error(&err);           /* any error: libjpeg exits nonzero */
    jpeg_create_decompress(&d);
    jpeg_mem_src(&d, dst, len);
    jpeg_read_header(&d, TRUE);
    assert(d.image_width == W && d.image_height == H && d.num_components == 3);
    assert(d.comp_info[0].h_samp_factor == 2 && d.comp_info[0].v_samp_factor == (v2 ? 2 : 1));
    d.out_color_space = JCS_YCbCr;
    d.do_fancy_upsampling = FALSE;
    jpeg_start_decompress(&d);
    while (d.output_scanline < H) {
        uint8_t *row = pix + d.output_scanline * W * 3;
        jpeg_read_scanlines(&d, &row, 1);
    }
    jpeg_finish_decompress(&d);
    jpeg_destroy_decompress(&d);
    for (unsigned y = 0; y < H; y++) {
        for (unsigned x = 0; x < W; x++) {
            const uint8_t *p = pix + (y * W + x) * 3;
            assert(abs(p[0] - Y(x, y)) <= tol);
            assert(abs(p[1] - U(x, y)) <= tol && abs(p[2] - V(x, y)) <= tol);
        }
    }
}

int main(void)
{
    uint8_t fine[2][64], coarse[2][64];

    memset(fine, 1, sizeof(fine));
    memcpy(coarse[0], std_lum_q, 64);
    memcpy(coarse[1], std_lum_q, 64);
    check(false, fine, 2);
    check(true, fine, 2);
    check(true, coarse, 24);
    printf("ok\n");
    return 0;
}
